function validarPS(respuesta){
    if(respuesta===('A')){
        alert ("¡Respuesta incorreta!")
    } if (respuesta===('B')){
        alert ("¡Respuesta correcta")
    }
}
function validarPC(respuesta){
    if(respuesta===('B')){
        alert ("¡Respuesta incorrecta!")
    } if (respuesta===('A')){
        alert("¡Respuesta correcta!")
    }
}